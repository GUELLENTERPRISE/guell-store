const ICON_MAP = {
  visa: VisaIcon,
  mastercard: MastercardIcon,
  paypal: PayPalIcon,
  amex: AmexIcon,
  applepay: ApplePayIcon,
  googlepay: GooglePayIcon,
} as const;

const PaymentIcons = () => {
  const { data: settings } = useStorefrontSettings();
  const raw = settings?.cart_payment_icons;
  const selected: string[] | null =
    raw === undefined || raw === null
      ? null
      : Array.isArray(raw)
        ? raw.map((id) => String(id).toLowerCase())
        : typeof raw === 'string'
          ? raw.split(',').map((s) => s.trim().toLowerCase()).filter(Boolean)
          : null;

  const iconsToShow =
    selected === null
      ? (Object.keys(ICON_MAP) as (keyof typeof ICON_MAP)[])
      : selected
          .filter((id): id is keyof typeof ICON_MAP => id in ICON_MAP)
          .map((id) => id as keyof typeof ICON_MAP);

  if (iconsToShow.length === 0) return null;

  return (
    <div className="flex items-center justify-center gap-3 pt-4">
      {iconsToShow.map((key) => {
        const Icon = ICON_MAP[key];
        return <Icon key={key} className="h-7 opacity-70" />;
      })}
    </div>
  );
};

export default PaymentIcons;
